import { readMigrationFiles } from 'drizzle-orm/migrator';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function createSupabaseSetupSql() {
  const migrations = readMigrationFiles({ migrationsFolder: './db/migrations' });
  const blocks = migrations
    .map(
      (migration) => `
  IF EXISTS (SELECT 1 FROM drizzle.__drizzle_migrations WHERE created_at = ${migration.folderMillis} AND hash <> '${migration.hash}') THEN
    RAISE EXCEPTION 'The migration journal differs from this setup file. Use the current application migrations.';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM drizzle.__drizzle_migrations WHERE created_at >= ${migration.folderMillis}) THEN
${migration.sql
  .join('\n')
  .trim()
  .split('\n')
  .map((line) => line.replace(/^\t+/, (tabs) => '  '.repeat(tabs.length)))
  .map((line) => (line.trim() ? '    ' + line.trimEnd() : ''))
  .join('\n')}
    INSERT INTO drizzle.__drizzle_migrations (hash, created_at)
    VALUES ('${migration.hash}', ${migration.folderMillis});
  END IF;`,
    )
    .join('\n');
  return `-- Mellowoof: run this entire file in Supabase SQL Editor.
-- Generated by npm run db:setup-sql from the committed Drizzle migrations.
-- Transactional and repeatable; existing application rows are preserved.
-- Unexpected existing table names or migration hashes cause a rollback.
-- Do not run this concurrently with another migration command.
BEGIN;
SELECT pg_advisory_xact_lock(6845351021);
CREATE SCHEMA IF NOT EXISTS drizzle;
CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);
DO $mellowoof_setup$
BEGIN
${blocks}
END
$mellowoof_setup$;
COMMIT;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  writeFileSync('docs/SUPABASE_SETUP.sql', createSupabaseSetupSql());
  console.log('Wrote docs/SUPABASE_SETUP.sql from the migration journal.');
}
